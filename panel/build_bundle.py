"""Packs the project files into panel/project-bundle.js.

The panel's "Upload / update project" button commits them to the GitHub repository.
Run after every code change:  python panel/build_bundle.py
"""

import base64
import json
from datetime import datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PATTERNS = [
    "*.py",
    "requirements.txt",
    ".env.example",
    ".gitignore",
    "README.md",
    "LICENSE",
    ".github/workflows/*.yml",
    "panel/*.html",
    "panel/*.css",
    "panel/app.js",
    "panel/crypto.js",
    "panel/icon.ico",
    "panel/*.py",
    "tools/*.py",
    "*.bat",
]


def main() -> None:
    files = []
    for pattern in PATTERNS:
        for path in sorted(ROOT.glob(pattern)):
            rel = path.relative_to(ROOT).as_posix()
            if path.name == ".env":
                continue
            files.append({"path": rel, "b64": base64.b64encode(path.read_bytes()).decode("ascii")})
    bundle = {"built": datetime.now().strftime("%Y-%m-%d %H:%M"), "files": files}
    out = ROOT / "panel" / "project-bundle.js"
    out.write_text(
        "/* Generated by panel/build_bundle.py, do not edit by hand. */\n"
        f"window.PROJECT_BUNDLE = {json.dumps(bundle)};\n",
        encoding="utf-8",
    )
    print(f"{out.name}: {len(files)} files")
    for f in files:
        print("  ", f["path"])


if __name__ == "__main__":
    main()
